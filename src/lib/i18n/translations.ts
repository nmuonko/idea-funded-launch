// Helper function to get translated status
export function getStatusTranslation(status: string, lang: Language): string {
  const t = getAdminTranslation(lang);
  const statusMap: Record<string, keyof typeof adminTranslations.en.status> = {
    'DRAFT': 'draft',
    'PENDING_PAYMENT': 'pendingPayment',
    'PENDING': 'pending',
    'PAID': 'paid',
    'PROCESSING': 'processing',
    'SHIPPED': 'shipped',
    'READY_FOR_PICKUP': 'readyForPickup',
    'DELIVERED': 'delivered',
    'COMPLETED': 'completed',
    'CANCELLED': 'cancelled',
    'FAILED': 'failed',
    'paid': 'paid',
    'pending': 'pending',
    'failed': 'failed',
    'cancelled': 'cancelled',
    'verified': 'verified',
    'unverified': 'unverified',
  };
  
  const key = statusMap[status];
  return key ? t.status[key] : status;
}

