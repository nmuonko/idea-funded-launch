/**
 * Get template queries for a section
 */
export function getTemplateQueries(sectionKey: string): string[] {
  return TEMPLATE_LIBRARY[sectionKey] || [];
}

/**
 * Get random subset of template queries for suggestions
 */
export function getRandomTemplateQueries(sectionKey: string, count: number): string[] {
  const templates = getTemplateQueries(sectionKey);
  if (templates.length <= count) return [...templates];
  
  // Fisher-Yates shuffle and take first N
  const shuffled = [...templates];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}
